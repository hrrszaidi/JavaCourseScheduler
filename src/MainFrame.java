    private void scheduleClassesSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_scheduleClassesSubmitActionPerformed
        // TODO add your handling code here:
        String selectedCourseCode = selectClassesComboBox.getSelectedItem().toString();
        StudentEntry selectedStudent = (StudentEntry) selectStudentComboBox.getSelectedItem();
        ScheduleEntry schedule;
        
        int scheduleStudentCount = ScheduleQueries.getScheduleStudentCount(currentSemester, selectedCourseCode);
        
        java.sql.Timestamp currentTimeStamp = new java.sql.Timestamp(Calendar.getInstance().getTime().getTime());
        
        if (scheduleStudentCount < ClassQueries.getClassSeats(currentSemester, selectedCourseCode)){
            schedule = new ScheduleEntry(currentSemester,selectedCourseCode,selectedStudent.getStudentID(),"S",currentTimeStamp);
            scheduleClassesLabel.setText(selectedStudent + " has been added for class " + selectedCourseCode + ".");
        }   
        else{
            schedule = new ScheduleEntry(currentSemester,selectedCourseCode,selectedStudent.getStudentID(),"W",currentTimeStamp);
            scheduleClassesLabel.setText(selectedStudent + " has been waitlisted for class " + selectedCourseCode + ".");
        }
        ScheduleQueries.addScheduleEntry(schedule);
    }//GEN-LAST:event_scheduleClassesSubmitActionPerformed

