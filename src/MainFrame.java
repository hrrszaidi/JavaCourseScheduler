    private void dropStudentSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dropStudentSubmitButtonActionPerformed
        // TODO add your handling code here:
        StudentEntry selectedStudent = (StudentEntry) chooseStudentComboBox.getSelectedItem();
        ArrayList<String> semesters = SemesterQueries.getSemesterList();
        ArrayList<ArrayList<ScheduleEntry>> scheduleBySemester = new ArrayList<ArrayList<ScheduleEntry>>();
        for (String semester: semesters){
            scheduleBySemester.add(ScheduleQueries.getScheduleByStudent(semester, selectedStudent.getStudentID()));
        }
        int i = 0;
        String result = String.format("%s has been dropped from the list. \n",selectedStudent);
        for (ArrayList<ScheduleEntry> schedules: scheduleBySemester){
            result += String.format("\nFor Semester: %s\n", semesters.get(i));
            for (ScheduleEntry schedule: schedules){
                
                ScheduleQueries.dropStudentScheduleByCourse(schedule.getSemester(), selectedStudent.getStudentID(), schedule.getCourseCode());
                result += String.format("%s has been dropped from %s\n", selectedStudent, schedule.getCourseCode());
                ArrayList<ScheduleEntry> waitlistList = ScheduleQueries.getWaitlistedStudentsByClass(schedule.getSemester(), schedule.getCourseCode());
                if(!waitlistList.isEmpty() && schedule.getStatus().equals("S")){
                    ScheduleEntry waitlist = waitlistList.get(0);
                    StudentEntry waitlistedStudent =  StudentQueries.getStudent(waitlist.getStudentID());
                    ScheduleQueries.updateScheduleEntry(waitlistList.get(0));
                    result += String.format("%s has been scheduled into %s\n", waitlistedStudent, waitlist.getCourseCode());
                }
            }
            i++;
        }
        StudentQueries.dropStudent(selectedStudent.getStudentID());
        dropStudentTextArea.setText(result);
        rebuildSelectStudentComboBox();
    }//GEN-LAST:event_dropStudentSubmitButtonActionPerformed

    private void dropClassSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dropClassSubmitButtonActionPerformed
        // TODO add your handling code here:
        String courseCode = dropClassComboBox.getSelectedItem().toString();
        ArrayList<StudentEntry> waitlistedStudent = MultiTableQueries.getWaitlistedStudentsByClass(currentSemester, courseCode);
        ArrayList<StudentEntry> scheduledStudent = MultiTableQueries.getScheduledStudentsByClass(currentSemester,courseCode);
        
        String result = "Scheduled students dropped from the course:\n";
        for (StudentEntry student: scheduledStudent){
            result += String.format("%s\n", student);
        }
        
        result += "\nWaitlisted Students dropped from the class\n";
        for(StudentEntry student: waitlistedStudent){
            result += String.format("%s\n",student);
        }
        
        dropClassTextArea.setText(result);
        ScheduleQueries.dropScheduleByCourse(currentSemester,courseCode);
        ClassQueries.dropClass(currentSemester,courseCode);
        
        rebuildSelectClassesComboBox();

    }//GEN-LAST:event_dropClassSubmitButtonActionPerformed

